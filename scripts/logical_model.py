"""Logical model as a Mermaid erDiagram, generated from the dbt project (target/manifest.json).

Source of truth is the dbt YAML, so the diagram cannot drift from the models:
  - entities: meta.logical_entity on a model (one name or a list); a column's meta.logical_entity overrides it for
    the relationships of that column (for example the owner changes inside the deal history)
  - keys: meta.primary_key on a model
  - relationships, solid: the relationships tests and the foreign_key constraints of the contracted models; the
    parent side is mandatory when the child column is tested not_null
  - relationships, solid, tested outside the model: column meta.references_entity (for example a custom raw test)
  - relationships, dotted (expected by the business, not supported by the data): column meta.intended_entity

Usage (after dbt parse, compile or build):
  python3 scripts/logical_model.py                     # print the Markdown block
  python3 scripts/logical_model.py --write <note.md>   # replace the block between the markers in a note
"""

import argparse
import json
import re
from pathlib import Path

BEGIN = "<!-- BEGIN generated by scripts/logical_model.py -->"
END = "<!-- END generated by scripts/logical_model.py -->"


def meta_of(item):
    # dbt keeps meta both at the top level and under config; merge the two
    return {**item.get("meta", {}), **item.get("config", {}).get("meta", {})}


def as_list(value):
    if value is None:
        return []
    return value if isinstance(value, list) else [value]


def load(manifest_path):
    manifest = json.loads(Path(manifest_path).read_text())
    models = {uid: n for uid, n in manifest["nodes"].items() if n["resource_type"] == "model"}
    tests = [n for n in manifest["nodes"].values() if n["resource_type"] == "test"]
    return models, tests


def build(models, tests):
    entities = {}      # entity -> {"models": [...], "keys": {column: type}}
    model_entity = {}  # model unique_id -> first entity
    for uid, node in models.items():
        names = as_list(meta_of(node).get("logical_entity"))
        if not names:
            continue
        model_entity[uid] = names[0]
        for name in names:
            entity = entities.setdefault(name, {"models": [], "keys": {}})
            entity["models"].append(node["name"])
        for column in as_list(meta_of(node).get("primary_key")):
            col = node["columns"].get(column, {})
            entities[names[0]]["keys"][column] = (col.get("data_type") or "key").split("(")[0].lower()

    # columns tested not_null (or constrained not_null), per model
    not_null = set()
    for test in tests:
        if test.get("test_metadata", {}).get("name") == "not_null":
            not_null.add((test["attached_node"], test.get("column_name")))
    for uid, node in models.items():
        for column, col in node["columns"].items():
            if any(c.get("type") == "not_null" for c in col.get("constraints", [])):
                not_null.add((uid, column))

    def child_entity(uid, column):
        col_meta = meta_of(models[uid]["columns"].get(column, {}))
        return as_list(col_meta.get("logical_entity"))[0] if col_meta.get("logical_entity") else model_entity.get(uid)

    edges = {}  # (parent, child) -> {"columns": set, "mandatory": bool, "dotted": bool}

    def add(parent, child, column, mandatory, dotted=False):
        if not parent or not child or parent == child:
            return
        edge = edges.setdefault((parent, child), {"columns": set(), "mandatory": mandatory, "dotted": dotted})
        edge["columns"].add(column)
        edge["mandatory"] = edge["mandatory"] and mandatory

    # relationships tests
    for test in tests:
        if test.get("test_metadata", {}).get("name") != "relationships":
            continue
        child_uid, column = test["attached_node"], test.get("column_name")
        if child_uid not in models:
            continue
        parents = [d for d in test["depends_on"]["nodes"] if d != child_uid and d in models]
        for parent_uid in parents:
            add(model_entity.get(parent_uid), child_entity(child_uid, column), column, (child_uid, column) in not_null)

    # foreign_key constraints of contracted models
    by_name = {n["name"]: uid for uid, n in models.items()}
    for uid, node in models.items():
        for constraint in node.get("constraints", []):
            if constraint.get("type") != "foreign_key":
                continue
            match = re.search(r"ref\(['\"]([^'\"]+)['\"]\)", constraint.get("to") or "")
            if not match or match.group(1) not in by_name:
                continue
            for column in constraint.get("columns", []):
                add(model_entity.get(by_name[match.group(1)]), child_entity(uid, column), column, (uid, column) in not_null)

    # relationships declared in column meta
    for uid, node in models.items():
        for column, col in node["columns"].items():
            col_meta = meta_of(col)
            if col_meta.get("references_entity"):
                add(col_meta["references_entity"], child_entity(uid, column), column, (uid, column) in not_null)
            if col_meta.get("intended_entity"):
                add(col_meta["intended_entity"], child_entity(uid, column), column, False, dotted=True)

    return entities, edges


def render(entities, edges):
    lines = [BEGIN, "", "```mermaid", "erDiagram"]
    for (parent, child), edge in sorted(edges.items()):
        parent_end = "||" if edge["mandatory"] else "|o"
        line = ".." if edge["dotted"] else "--"
        label = ", ".join(sorted(edge["columns"])) + (" (not supported by the data)" if edge["dotted"] else "")
        lines.append(f'    {parent} {parent_end}{line}o{{ {child} : "{label}"')
    fk_columns = {}
    for (parent, child), edge in edges.items():
        if not edge["dotted"]:
            fk_columns.setdefault(child, set()).update(edge["columns"])
    # entities named only on a column (for example OWNER_ASSIGNMENT) still get a block
    for parent, child in edges:
        for name in (parent, child):
            entities.setdefault(name, {"models": [], "keys": {}})
    for name in sorted(entities):
        attributes = [f"        {dtype} {column} PK" for column, dtype in entities[name]["keys"].items()]
        attributes += [f"        key {column} FK" for column in sorted(fk_columns.get(name, set()) - set(entities[name]["keys"]))]
        if not attributes:
            continue  # an entity without keys is drawn by its relationships only
        lines += [f"    {name} {{", *attributes, "    }"]
    lines += ["```", "", "| Entity | dbt models |", "|---|---|"]
    for name in sorted(entities):
        models = ", ".join(f"`{m}`" for m in sorted(set(entities[name]["models"]))) or "named on a column only"
        lines.append(f"| {name} | {models} |")
    lines += ["", END]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--manifest", default="target/manifest.json")
    parser.add_argument("--write", help="Markdown note whose block between the markers is replaced")
    args = parser.parse_args()
    block = render(*build(*load(args.manifest)))
    if not args.write:
        print(block)
        return
    note = Path(args.write)
    text = note.read_text()
    if BEGIN not in text or END not in text:
        raise SystemExit(f"{note}: add the two marker lines first:\n{BEGIN}\n{END}")
    start, end = text.index(BEGIN), text.index(END) + len(END)
    note.write_text(text[:start] + block + text[end:])
    print(f"{note}: logical model updated")


if __name__ == "__main__":
    main()
